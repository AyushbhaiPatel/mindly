const ADJECTIVE_INDEX = new Map<string, number>(ADJECTIVES.map((w, i) => [w, i]));
const NOUN_INDEX = new Map<string, number>(NOUNS.map((w, i) => [w, i]));

/** Number of hex digits a codename encodes: the last 6 of the compact id (24 bits). */
const CODENAME_HEX = 6;

/**
 * A readable name for an id, the same every time: `quiet-otter-17`. It spells out the last 6 hex
 * digits of the id (dashes removed): the adjective is the first byte, the noun the second and the
 * number the third, so two records share a name only when their ids end in the same 6 digits.
 * Works on a full id or any id or short id with at least 6 hex digits (a session tag like
 * `4409d433` gets the same name as its full id). Shown wherever people used to see the short id
 * and accepted by every command that takes an id. Input that does not end in 6 hex digits is
 * returned as its short id.
 */
export function codename(id: string): string {
  const tail = id.replace(/-/g, '').toLowerCase().slice(-CODENAME_HEX);
  if (!/^[0-9a-f]{6}$/.test(tail)) return shortId(id);
  const bits = Number.parseInt(tail, 16);
  const adjective = ADJECTIVES[(bits >> 16) & 0xff] as string;
  const noun = NOUNS[(bits >> 8) & 0xff] as string;
  return `${adjective}-${noun}-${bits & 0xff}`;
}

const CODENAME_RE = /^([a-z]{3,8})-([a-z]{3,8})-(0|[1-9][0-9]{0,2})$/;

/**
 * The 6 hex digits a {@link codename} stands for (`quiet-otter-17` -> `260011`), or null when
 * `input` is not a name: both words must be in the lists and the number 0 to 255 without
 * leading zeros. Case and surrounding spaces are ignored.
 */
export function parseCodename(input: string): string | null {
  const m = CODENAME_RE.exec(input.trim().toLowerCase());
  if (m === null) return null;
  const adjective = ADJECTIVE_INDEX.get(m[1] as string);
  const noun = NOUN_INDEX.get(m[2] as string);
  const n = Number(m[3]);
  if (adjective === undefined || noun === undefined || n > 0xff) return null;
  return ((adjective << 16) | (noun << 8) | n).toString(16).padStart(CODENAME_HEX, '0');
}
